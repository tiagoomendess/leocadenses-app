#!/usr/bin/env bash
# Writes /etc/nginx/snippets/cloudflare-allow.conf: `allow` lines for Cloudflare's current IP
# ranges and `deny all`, so the site only answers requests that came through Cloudflare.
# Run as root, then reload nginx. Re-run now and then (e.g. monthly from cron): Cloudflare
# publishes its ranges at https://www.cloudflare.com/ips/.
set -euo pipefail

target=/etc/nginx/snippets/cloudflare-allow.conf
tmp="$(mktemp)"

{
	echo "# Generated by update-cloudflare-ips.sh on $(date -u +%F). Do not edit."
	for list in ips-v4 ips-v6; do
		curl -fsS "https://www.cloudflare.com/$list" | while read -r range; do
			[[ -n "$range" ]] && echo "allow $range;"
		done
	done
	echo "allow 127.0.0.1;"
	echo "deny all;"
} >"$tmp"

# Refuse an empty or truncated download: that would lock everyone out.
if [[ "$(grep -c '^allow' "$tmp")" -lt 10 ]]; then
	echo "Cloudflare IP list looks incomplete, keeping the current file." >&2
	exit 1
fi

mkdir -p "$(dirname "$target")"
mv "$tmp" "$target"
chmod 644 "$target"
nginx -t
echo "Wrote $target. Reload nginx: systemctl reload nginx"
